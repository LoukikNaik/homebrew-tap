#!/usr/bin/env python3
"""Generate the Apple Silicon formula from a released PyPI wheel set."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile
from urllib.parse import unquote, urlparse
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "locks/macos-arm64-python312.json"


def fetch_metadata(version: str | None) -> dict:
    suffix = f"/{version}" if version else ""
    with urlopen(f"https://pypi.org/pypi/podclipper{suffix}/json", timeout=60) as response:
        return json.load(response)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default="", help="Released version; defaults to latest PyPI release")
    parser.add_argument("--report", type=Path, help="Use an existing pip resolution report")
    parser.add_argument("--if-new", action="store_true", help="Keep existing pins when already on this version")
    args = parser.parse_args()
    if args.version and not re.fullmatch(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", args.version):
        parser.error("Use a stable version such as 0.1.0, without the v prefix")
    metadata = fetch_metadata(args.version or None)
    version = metadata["info"]["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise SystemExit("Only stable X.Y.Z releases are supported")
    if args.if_new and LOCK.exists() and json.loads(LOCK.read_text())["version"] == version:
        print(f"Already on PodClipper {version}; keeping the existing dependency pins")
        return
    if metadata["info"]["name"] != "podclipper" or metadata["info"].get("license_expression") != "AGPL-3.0-only":
        raise SystemExit("Unexpected project name or license in PyPI metadata")
    source = next(f for f in metadata["urls"] if f["packagetype"] == "sdist" and not f["yanked"])
    if args.report:
        report = json.loads(args.report.read_text())
    else:
        if platform.system() != "Darwin" or platform.machine() != "arm64" or sys.version_info[:2] != (3, 12):
            raise SystemExit("Resolve on an Apple Silicon Mac using Python 3.12")
        with tempfile.TemporaryDirectory(prefix="podclipper-resolve-") as temporary:
            report_path = Path(temporary) / "report.json"
            subprocess.run([
                sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
                "--only-binary=:all:", "--platform", "macosx_14_0_arm64", "--python-version", "3.12",
                "--implementation", "cp", "--abi", "cp312", "--abi", "abi3", "--abi", "none",
                "--report", str(report_path), f"podclipper=={version}",
            ], check=True)
            report = json.loads(report_path.read_text())
    wheels = []
    for item in report["install"]:
        name = re.sub(r"[-_.]+", "-", item["metadata"]["name"]).lower()
        package_version = item["metadata"]["version"]
        url = item["download_info"]["url"]
        sha256 = item["download_info"]["archive_info"]["hashes"]["sha256"]
        filename = unquote(urlparse(url).path.rsplit("/", 1)[-1])
        if urlparse(url).scheme != "https" or urlparse(url).hostname != "files.pythonhosted.org" or not filename.endswith(".whl"):
            raise SystemExit(f"Expected an official PyPI wheel: {url}")
        if not re.fullmatch(r"[a-f0-9]{64}", sha256) or not re.fullmatch(r"[a-z0-9-]+", name):
            raise SystemExit(f"Invalid package/hash: {name}")
        if not re.fullmatch(r"[A-Za-z0-9.+!_-]+", package_version):
            raise SystemExit(f"Invalid package version: {name}")
        wheels.append({"name": name, "version": package_version, "url": url, "sha256": sha256})
    wheels.sort(key=lambda item: item["name"])
    if len({item["name"] for item in wheels}) != len(wheels):
        raise SystemExit("Duplicate packages in resolution report")
    if not any(item["name"] == "podclipper" and item["version"] == version for item in wheels):
        raise SystemExit("The report does not contain the requested PodClipper release")
    header = f'''# Generated by scripts/update_formula.py; edit the generator instead.
# Native ML dependencies use checked, pinned upstream wheels in this custom tap.
class Podclipper < Formula
  include Language::Python::Virtualenv

  desc "Turn podcast videos into vertical reels with captions"
  homepage "https://github.com/LoukikNaik/PodClipper"
  url "{source["url"]}"
  sha256 "{source["digests"]["sha256"]}"
  license "AGPL-3.0-only"

  depends_on arch: :arm64
  depends_on macos: :sonoma
  depends_on "ffmpeg"
  depends_on "python@3.12"

  livecheck do
    url "https://pypi.org/pypi/podclipper/json"
    strategy :json do |json|
      json["info"]["version"]
    end
  end
'''
    resources = "".join(f'''
  resource "{item["name"]}" do
    url "{item["url"]}", using: :nounzip
    sha256 "{item["sha256"]}"
  end
''' for item in wheels)
    requirements = "\n".join(f'      {item["name"]}=={item["version"]} --hash=sha256:{item["sha256"]}' for item in wheels)
    installation = '''
  def install
    wheelhouse = buildpath/"wheelhouse"
    wheelhouse.mkpath
    resources.each do |wheel|
      wheel.verify_download_integrity(wheel.cached_download)
      cp wheel.cached_download, wheelhouse/wheel.downloader.basename
    end

    requirements = buildpath/"requirements.lock"
    requirements.write <<~EOS
''' + requirements + '''
    EOS

    python = Formula["python@3.12"].opt_bin/"python3.12"
    virtualenv_create(libexec, python, system_site_packages: false)
    system python, "-m", "pip", "--python=#{libexec}/bin/python", "install",
           "--no-index", "--find-links=#{wheelhouse}", "--only-binary=:all:",
           "--require-hashes", "--disable-pip-version-check", "-r", requirements
    bin.install_symlink libexec/"bin/podclipper"
    prefix.install "LICENSE", "NOTICE"
  end

  def caveats
    <<~EOS
      Run `podclipper init`, set LLM_API_KEY in .env, then run:
        podclipper "path/to/podcast.mp4"

      LLM_ENDPOINT and LLM_MODEL can also be set in .env.
      Local transcription and detection models download on first use.
    EOS
  end
end
'''
    (ROOT / "Formula").mkdir(exist_ok=True)
    LOCK.parent.mkdir(exist_ok=True)
    LOCK.write_text(json.dumps({"version": version, "platform": "macOS 14+ arm64", "python": "3.12", "wheels": wheels}, indent=2) + "\n")
    (ROOT / "Formula/podclipper.rb").write_text(header + resources + installation)
    print(f"Generated PodClipper {version} with {len(wheels)} pinned wheels")


if __name__ == "__main__":
    main()
